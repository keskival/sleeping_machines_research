#!/usr/bin/env python3
"""Index every experiment result so prior tests are findable (founder, 16 Oct 2026: "structure our experiments … even you
can't see what has been tested already").

Scans experiments/results/**/*.json and writes:
- experiments/index/experiments.csv: one row per result file (date first committed, family directory, host, battle,
  status, tag, stage/decision summary, up to four headline metrics), for grep/sort;
- experiments/index/EXPERIMENT_INDEX.md: counts by family and by battle, and the latest completed results per battle with
  their headline metrics.
Curated question ledgers (what was tried, what it showed, what follows) live beside it, e.g.
experiments/index/LANGUAGE_DEPTH_COMPOSITION_LEDGER.md. Rerun after each publication batch:
    .venv-docker/bin/python scripts/build_experiment_index.py
"""
import csv, collections, json, re, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]; RES = ROOT/'experiments/results'; OUT = ROOT/'experiments/index'
METRIC = re.compile(r'(nll|ppl|perplexity|auroc|auprc|accuracy|acc|mrr|ndcg|loss|bpc|rmse|total|score|log_lik|ll)$', re.I)


def first_commit_dates():
    out = subprocess.run(['git', 'log', '--diff-filter=A', '--format=@%cI', '--name-only', '--', 'experiments/results'], cwd=ROOT, capture_output=True, text=True).stdout
    dates, cur = {}, None
    for line in out.splitlines():
        if line.startswith('@'): cur = line[1:11]
        elif line.strip(): dates[line.strip()] = cur                                    # git log is newest first: the last assignment is the first commit
    return dates


def metrics(d):
    found = []
    for k, v in d.items():
        if len(found) >= 4: break
        if isinstance(v, (int, float)) and not isinstance(v, bool) and METRIC.search(k) and 'flops' not in k.lower(): found.append((k, v))
        elif isinstance(v, dict):
            for kk in ('nll', 'ppl', 'auroc', 'accuracy', 'mrr', 'total'):
                if isinstance(v.get(kk), (int, float)): found.append((f'{k}.{kk}', v[kk])); break
    return found


def summary(d):
    for k in ('stage', 'decision', 'scope', 'description', 'experiment'):
        if isinstance(d.get(k), str): return re.sub(r'\s+', ' ', d[k])[:160]
    return ''


def main():
    dates = first_commit_dates(); rows = []
    for p in sorted(RES.rglob('*.json')):
        rel = str(p.relative_to(ROOT))
        try: d = json.loads(p.read_text())
        except Exception: continue
        if not isinstance(d, dict): continue
        fam = p.relative_to(RES).parts[0] if len(p.relative_to(RES).parts) > 1 else '(top)'
        name = p.stem; host = 'aws' if name.startswith('aws') else ('curie' if name.startswith('curie') else '')
        m = metrics(d)
        rows.append(dict(date=dates.get(rel, ''), family=fam, host=host, battle=str(d.get('battle', '')), status=str(d.get('status', '')), tag=str(d.get('tag', name)),
                         summary=summary(d), metrics='; '.join(f'{k}={v:.4g}' for k, v in m), path=rel))
    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT/'experiments.csv').open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(sorted(rows, key=lambda r: (r['date'], r['path'])))
    fam = collections.defaultdict(list); bat = collections.defaultdict(list)
    for r in rows: fam[r['family']].append(r); bat[r['battle'] or '(none)'].append(r)
    L = ['# Experiment index', '', 'Generated by `scripts/build_experiment_index.py` from every result file under `experiments/results/` '
         f'({len(rows)} files). Full table: [experiments.csv](experiments.csv) (one row per result: date first committed, family, host, battle, '
         'status, tag, summary, headline metrics, path). Curated question ledgers:', '',
         '- [Language depth and composition](LANGUAGE_DEPTH_COMPOSITION_LEDGER.md): every attempt to get depth/composition in language, what it showed, what follows.', '',
         'Before designing an experiment, search the CSV for the mechanism, battle and data size (e.g. `grep -i part_whole experiments/index/experiments.csv`) '
         'and read the relevant ledger. Add new question ledgers here when a question accumulates more than a handful of runs.', '',
         '## By results family', '', '| family | files | completed | battles | first | last |', '| --- | --- | --- | --- | --- | --- |']
    for k in sorted(fam, key=lambda k: -len(fam[k])):
        rs = fam[k]; ds = sorted(r['date'] for r in rs if r['date']); bs = collections.Counter(r['battle'] for r in rs if r['battle'])
        L.append(f"| {k} | {len(rs)} | {sum(r['status'] == 'completed' for r in rs)} | {', '.join(b for b, _ in bs.most_common(3))} | {ds[0] if ds else ''} | {ds[-1] if ds else ''} |")
    L += ['', '## Latest completed results by battle (up to 12 each, newest first)', '']
    for b in sorted(bat, key=lambda k: -len(bat[k])):
        rs = sorted([r for r in bat[b] if r['status'] == 'completed' and r['metrics']], key=lambda r: (r['date'], r['path']), reverse=True)[:12]
        if not rs: continue
        L += [f'### {b} ({len(bat[b])} files)', '', '| date | tag | metrics | path |', '| --- | --- | --- | --- |']
        L += [f"| {r['date']} | {r['tag'][:60]} | {r['metrics'][:110]} | `{r['path']}` |" for r in rs] + ['']
    (OUT/'EXPERIMENT_INDEX.md').write_text('\n'.join(L) + '\n')
    print(json.dumps(dict(files=len(rows), families=len(fam), battles=len(bat))))


if __name__ == '__main__':
    main()
